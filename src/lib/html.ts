// Escape the five HTML-significant characters. Used wherever untrusted text is
// interpolated into an innerHTML string (fenced code, mention highlighting).
export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
